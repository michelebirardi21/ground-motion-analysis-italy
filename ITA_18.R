  B2 <- a_i + FD_term2 + FS_term2 + vect_reverse * f2_i + vect_strike * f1_i + FM_term2
  
  hh2_omo <- sqrt(tau_i^2 + phi_S2S_i^2 + phi_0_i^2)
  
  if (IM > 2) {
    hh2_etero <- rep(hh2_omo, ndata)
  } else {
    phi_0_et2 <- as.numeric(M < M2_i) * phi_0_1_i +
      as.numeric(M > M1_i & M < M2_i) * ((phi_0_2_i - phi_0_1_i) * (M - M1_i)) +
      as.numeric(M >= M2_i) * phi_0_2_i
    
    phi_S2S_et2 <- as.numeric(vs30 < V2_val) * phi_S2S_1_i +
      as.numeric(vs30 > V1_val & vs30 < V2_val) * ((phi_S2S_2_i - phi_S2S_1_i) * (log10(V2_val / vs30) / log10(V2_val / V1_val))) +
      as.numeric(vs30 >= V2_val) * phi_S2S_2_i
    
    hh2_etero <- sqrt(tau_i^2 + phi_S2S_et2^2 + phi_0_et2^2)
  }
  
  B  <- (B1 * peso2 + B2 * peso1) / (peso1 + peso2)
  hh_omo  <- (hh1_omo * peso2 + hh2_omo * peso1) / (peso1 + peso2)
  hh_etero <- (hh1_etero * peso2 + hh2_etero * peso1) / (peso1 + peso2)
  tau_omo <- rep((tau1_omo <- tau_v[ind1] * peso2 + tau_v[ind2] * peso1) / (peso1 + peso2), ndata)
  phi_S2S_omo <- rep((phi1_S2S_omo <- phi_S2S_v[ind1] * peso2 + phi_S2S_v[ind2] * peso1) / (peso1 + peso2), ndata)
  phi_0_omo <- rep((phi1_0_omo <- phi_0_v[ind1] * peso2 + phi_0_v[ind2] * peso1) / (peso1 + peso2), ndata)
}

pred <- 10^B
sigma_omo <- 10^hh_omo
sigma_etero <- log(10^hh_etero) # coerente con matlab originale
tau_out <- 10^tau_omo
phi_S2S_out <- 10^phi_S2S_omo
phi_0_out <- 10^phi_0_omo

return(list(pred = pred,
            sigma_omo = sigma_omo,
            sigma_etero = sigma_etero,
            tau = tau_out,
            phi_S2S = phi_S2S_out,
            phi_0 = phi_0_out))
}
  